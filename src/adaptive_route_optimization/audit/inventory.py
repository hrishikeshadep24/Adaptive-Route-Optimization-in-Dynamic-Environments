"""Claim Inventory for Pre-Phase 9 Audit.

Catalogs every material numerical claim, metric, and finding from:
- Phase 6 Evidence (docs/evidence/phase6_evidence.md)
- Phase 7 Evidence (docs/evidence/phase7_evidence.md)
- Research Findings Report (docs/RESEARCH_FINDINGS.md)
- Phase 8 Evidence (docs/evidence/phase8_evidence.md)
"""

from __future__ import annotations
from dataclasses import dataclass, asdict
from enum import Enum
from typing import Any, Optional


class ClaimStatus(str, Enum):
    PASS = "PASS"
    FAIL = "FAIL"
    INCONCLUSIVE = "INCONCLUSIVE"
    UNVERIFIABLE = "UNVERIFIABLE"


class MetricType(str, Enum):
    COUNT = "count"
    MEAN = "mean"
    MEDIAN = "median"
    PERCENTAGE = "percentage"
    RATIO = "ratio"
    DIFFERENCE = "difference"
    CONFIDENCE_INTERVAL = "confidence_interval"
    P_VALUE = "p_value"
    EFFECT_SIZE = "effect_size"
    STATUS = "status"


@dataclass(frozen=True)
class Claim:
    """Specification of an audited empirical claim."""
    claim_id: str
    phase: int
    source_doc: str
    section: str
    metric_name: str
    metric_type: MetricType
    claimed_value: Any
    tolerance: float  # Absolute or relative tolerance
    is_relative_tolerance: bool
    source_file: str
    recomputation_method: str
    description: str

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["metric_type"] = self.metric_type.value
        return d


